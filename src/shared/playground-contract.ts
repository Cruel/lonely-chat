export function validateFreeformSchema(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value))
    throw new Error('Response schema must be a JSON object.');
  let encoded: string;
  try {
    encoded = JSON.stringify(value);
  } catch {
    throw new Error('Response schema must be serializable JSON.');
  }
  if (!encoded || encoded.length > 32768)
    throw new Error('Response schema exceeds the 32 KiB limit.');
  if (Object.keys(value).length === 0) throw new Error('Response schema cannot be empty.');
  return JSON.parse(encoded) as Record<string, unknown>;
}

export function validatePlaygroundVideo(mode: unknown, video: unknown, frames: unknown) {
  if (mode !== undefined && mode !== 'frames' && mode !== 'native-video')
    throw new Error('Invalid Playground video mode.');
  if (mode !== 'native-video') {
    if (video !== undefined) throw new Error('Native video requires native-video mode.');
    return mode === undefined ? {} : { videoMode: 'frames' as const };
  }
  if (frames !== undefined && Array.isArray(frames) && frames.length)
    throw new Error('Choose either selected JPEG frames or native video, not both.');
  if (
    !video ||
    typeof video !== 'object' ||
    Array.isArray(video) ||
    Object.keys(video).join(',') !== 'token' ||
    !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      (video as { token?: unknown }).token as string,
    )
  )
    throw new Error('Choose a native video clip first.');
  return {
    videoMode: 'native-video' as const,
    video: { token: (video as { token: string }).token },
  };
}

export function validateVideoOverrides(mode: unknown, options: unknown) {
  if (options === undefined) return {};
  if (mode !== 'native-video') throw new Error('Video settings require native-video mode.');
  return { videoOptions: validateNativeVideoPreferences(options) };
}

export function validateImageTokenOverride(value: unknown) {
  if (value === undefined) return {};
  if (!validNumericPreference('imageMaxTokens', value))
    throw new Error('Invalid image token budget (expected 0–8192 in increments of 16).');
  return { imageMaxTokens: value };
}

export function validateFreeformRequest(value: unknown): FreeformRequest {
  if (!value || typeof value !== 'object' || Array.isArray(value))
    throw new Error('Invalid Playground request.');
  const v = value as Record<string, unknown>;
  if (
    Object.keys(v).sort().join(',') !==
    [
      'frames',
      'imageMaxTokens',
      'maxTokens',
      'modelId',
      'responseSchema',
      'seed',
      'systemPrompt',
      'temperature',
      'topK',
      'topP',
      'userPrompt',
      'video',
      'videoMode',
      'videoOptions',
    ]
      .filter((key) => Object.hasOwn(v, key))
      .join(',')
  )
    throw new Error('Invalid Playground request fields.');
  if (typeof v.modelId !== 'string' || v.modelId.length < 1 || v.modelId.length > 200)
    throw new Error('Select an installed model.');
  if (
    typeof v.systemPrompt !== 'string' ||
    v.systemPrompt.length > 8000 ||
    typeof v.userPrompt !== 'string' ||
    !v.userPrompt.trim() ||
    v.userPrompt.length > 16000
  )
    throw new Error('Enter a user prompt (up to 16,000 characters); system prompt limit is 8,000.');
  function range(key: string, low: number, high: number, integer = false): number {
    const n = v[key];
    if (
      typeof n !== 'number' ||
      !Number.isFinite(n) ||
      n < low ||
      n > high ||
      (integer && !Number.isInteger(n))
    )
      throw new Error(`Invalid ${key}: expected ${low}–${high}.`);
    return n;
  }
  return {
    modelId: v.modelId,
    systemPrompt: v.systemPrompt,
    userPrompt: v.userPrompt,
    temperature: range('temperature', 0, 2),
    topP: range('topP', 0, 1),
    topK: range('topK', 1, 200, true),
    maxTokens: range('maxTokens', 1, 8192, true),
    seed: range('seed', 0, 2147483647, true),
    ...(v.responseSchema === undefined
      ? {}
      : { responseSchema: validateFreeformSchema(v.responseSchema) }),
    ...(v.frames === undefined ? {} : { frames: validatePlaygroundFrames(v.frames) }),
    ...validatePlaygroundVideo(v.videoMode, v.video, v.frames),
    ...validateVideoOverrides(v.videoMode, v.videoOptions),
    ...validateImageTokenOverride(v.imageMaxTokens),
  };
}
